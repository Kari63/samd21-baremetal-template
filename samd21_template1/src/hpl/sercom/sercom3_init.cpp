#include "samd21.h"
#include "sercom_init.h"

void sercom3_init(void)
{
	SERCOM3->SPI.CTRLA.bit.ENABLE = 0;
	while (SERCOM3->SPI.SYNCBUSY.bit.ENABLE) {
	}

	PM->APBCMASK.reg |= PM_APBCMASK_SERCOM3;

	GCLK->CLKCTRL.reg = (uint16_t)(
		GCLK_CLKCTRL_ID(SERCOM3_GCLK_ID_CORE) |
		GCLK_CLKCTRL_GEN_GCLK0 |
		GCLK_CLKCTRL_CLKEN);
	while (GCLK->STATUS.bit.SYNCBUSY) {
	}

	SERCOM3->SPI.CTRLA.reg = SERCOM_SPI_CTRLA_SWRST;
	while (SERCOM3->SPI.SYNCBUSY.bit.SWRST) {
	}

	PORT->Group[0].PINCFG[18].reg = PORT_PINCFG_PMUXEN;
	PORT->Group[0].PMUX[9].bit.PMUXE = PORT_PMUX_PMUXE_D_Val;
	PORT->Group[0].PINCFG[19].reg = PORT_PINCFG_PMUXEN;
	PORT->Group[0].PMUX[9].bit.PMUXO = PORT_PMUX_PMUXO_D_Val;

	SERCOM3->SPI.CTRLA.reg =
		SERCOM_SPI_CTRLA_MODE(3) |
		SERCOM_SPI_CTRLA_DOPO(1) |
		SERCOM_SPI_CTRLA_DIPO(0);
	SERCOM3->SPI.CTRLB.reg = SERCOM_SPI_CTRLB_CHSIZE(0);
	while (SERCOM3->SPI.SYNCBUSY.bit.CTRLB) {
	}

	SERCOM3->SPI.BAUD.reg = 1;
	SERCOM3->SPI.CTRLA.bit.ENABLE = 1;
	SERCOM3->SPI.INTFLAG.reg = SERCOM_SPI_INTFLAG_TXC;
	while (SERCOM3->SPI.SYNCBUSY.bit.ENABLE) {
	}
}
