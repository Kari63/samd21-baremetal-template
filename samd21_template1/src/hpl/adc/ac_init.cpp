#include "samd21.h"

void ac_init(void)


{
	REG_AC_CTRLA = 0; 
	
	PM->APBCMASK.reg |= PM_APBCMASK_AC;
	
	GCLK->CLKCTRL.reg = 
	GCLK_CLKCTRL_ID(AC_GCLK_ID_DIG) | 
	GCLK_CLKCTRL_GEN_GCLK1 | 
	GCLK_CLKCTRL_CLKEN;
	while (GCLK->STATUS.bit.SYNCBUSY);

	GCLK->CLKCTRL.reg = 
	GCLK_CLKCTRL_ID(AC_GCLK_ID_ANA) | 
	GCLK_CLKCTRL_GEN_GCLK1 | 
	GCLK_CLKCTRL_CLKEN;
	
	while (GCLK->STATUS.bit.SYNCBUSY);
	
	
	// PA04 → AIN0 → COMP0+
	PORT->Group[0].PINCFG[4].bit.PMUXEN = 1;
	PORT->Group[0].PMUX[2].bit.PMUXE = PORT_PMUX_PMUXE_B_Val;   // Function B

	// PA05 → AIN1 → COMP0-
	PORT->Group[0].PINCFG[5].bit.PMUXEN = 1;
	PORT->Group[0].PMUX[2].bit.PMUXO = PORT_PMUX_PMUXO_B_Val;   // Function B

	// PA06 → AIN2 → COMP1+
	PORT->Group[0].PINCFG[6].bit.PMUXEN = 1;
	PORT->Group[0].PMUX[3].bit.PMUXE = PORT_PMUX_PMUXE_B_Val;   // Function B

	// PA07 → AIN3 → COMP1-
	PORT->Group[0].PINCFG[7].bit.PMUXEN = 1;
	PORT->Group[0].PMUX[3].bit.PMUXO = PORT_PMUX_PMUXO_B_Val;   // Function B


	REG_AC_COMPCTRL0 =
	AC_COMPCTRL_HYST |
	AC_COMPCTRL_INTSEL_TOGGLE |      // (correct mask)
	AC_COMPCTRL_MUXNEG_VSCALE |      // VSCALE in use
	AC_COMPCTRL_MUXPOS_PIN0 |
	AC_COMPCTRL_ENABLE;

	REG_AC_COMPCTRL1 =
	AC_COMPCTRL_HYST |
	AC_COMPCTRL_INTSEL_RISING |      // (correct mask)
	AC_COMPCTRL_MUXNEG_VSCALE |      // VSCALE in use
	AC_COMPCTRL_MUXPOS_PIN2 |
	AC_COMPCTRL_ENABLE;

	REG_AC_SCALER0 = AC_SCALER_VALUE(32);
	REG_AC_SCALER1 = AC_SCALER_VALUE(32);

	REG_AC_INTENSET = AC_INTENSET_COMP0 ;

	REG_AC_CTRLA = AC_CTRLA_ENABLE;
   
	NVIC_ClearPendingIRQ(AC_IRQn);
	NVIC_EnableIRQ(AC_IRQn);
}
